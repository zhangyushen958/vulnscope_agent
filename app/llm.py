"""OpenAI-compatible chat-completions with model-directed function calling.

No browsing tools are available. Tool schemas are generated by our own agent.
"""
from __future__ import annotations
import json
import re
import time
from dataclasses import dataclass
from typing import Any, Protocol
import httpx
from app.config import Settings


@dataclass
class ToolCall:
    id: str
    name: str
    arguments: dict[str, Any]


@dataclass
class ModelTurn:
    message: dict
    calls: list[ToolCall]
    finish_reason: str | None = None


class ModelClient(Protocol):
    def complete(self, messages: list[dict], tools: list[dict]) -> ModelTurn: ...


class OpenAICompatibleClient:
    def __init__(self, settings: Settings, transport: httpx.BaseTransport | None = None,
                 thinking: str = "disabled"):
        self.settings = settings
        self.transport = transport
        if thinking not in {"enabled", "disabled"}:
            raise ValueError("thinking 必须是 enabled 或 disabled")
        self.thinking = thinking
        self.settings.validate_llm_url()

    def complete(self, messages: list[dict], tools: list[dict], *,
                 tool_choice: str | dict | None = None) -> ModelTurn:
        if not self.settings.llm_api_key and not self.settings.llm_base_url.startswith("http://localhost") and not self.settings.llm_base_url.startswith("http://127.0.0.1"):
            raise RuntimeError("未配置 VULNSCOPE_LLM_API_KEY；真实漏洞判定需要支持工具调用的 LLM")
        base = self.settings.llm_base_url.rstrip("/")
        if base == "https://api.deepseek.com":
            base += "/v1"
        url = base + "/chat/completions"
        headers = {"Content-Type": "application/json"}
        if self.settings.llm_api_key:
            headers["Authorization"] = "Bearer " + self.settings.llm_api_key
        request_model = self.settings.llm_model
        host = (httpx.URL(self.settings.llm_base_url).host or "").lower()
        is_bailian = host.endswith(".maas.aliyuncs.com")
        is_official_deepseek = host == "api.deepseek.com"

        # The same model has different public identifiers on DeepSeek's own API
        # and on Alibaba Cloud Model Studio.
        if is_official_deepseek and request_model == "deepseek-v4.1-flash-1017":
            request_model = "deepseek-flash"

        # A plain `auto` request lets the model decide that no tool is needed.
        # VulnScope's Agent protocol, however, expects a tool action on every
        # decision turn. For Bailian DeepSeek V4 in non-thinking mode, use
        # `required` so the model must return at least one tool call.
        # Thinking mode does not support forced tool_choice on this endpoint,
        # so it intentionally remains `auto`. Callers (such as the API probe)
        # may explicitly override this policy.
        if tool_choice is None:
            effective_tool_choice = (
                "required" if is_bailian and tools and self.thinking == "disabled"
                else "auto"
            )
        else:
            effective_tool_choice = tool_choice
        if isinstance(effective_tool_choice, str):
            if effective_tool_choice not in ("auto", "none", "required"):
                raise ValueError("tool_choice 仅支持 auto、none、required 或函数指定对象")
        elif not isinstance(effective_tool_choice, dict):
            raise ValueError("tool_choice 仅支持 auto、none、required 或函数指定对象")
        if self.thinking == "enabled" and (effective_tool_choice == "required" or isinstance(effective_tool_choice, dict)):
            raise ValueError("阿里云百炼思考模式不支持强制 tool_choice，请关闭思考模式后测试")

        body = {"model": request_model, "messages": messages, "tools": tools,
                "tool_choice": effective_tool_choice,
                "max_tokens": 8192 if self.thinking == "enabled" else 2400}
        # Model Studio's OpenAI-compatible Chat Completions API uses the
        # non-standard enable_thinking field. Direct HTTP requests send it at
        # the JSON top level (the OpenAI Python SDK would use extra_body).
        if is_bailian:
            body["enable_thinking"] = self.thinking == "enabled"
        elif is_official_deepseek:
            body["thinking"] = {"type": self.thinking}
        with httpx.Client(timeout=httpx.Timeout(100, connect=10), follow_redirects=False,
                          transport=self.transport) as client:
            response = None
            for attempt in range(3):
                response = client.post(url, headers=headers, json=body)
                if response.status_code not in (429, 500, 502, 503, 504) or attempt >= 2:
                    break
                retry_after = response.headers.get("retry-after")
                try:
                    delay = max(0.0, float(retry_after)) if retry_after else float(2 ** attempt)
                except ValueError:
                    delay = float(2 ** attempt)
                # Honor a short provider cooldown; do not keep a batch worker
                # blocked for a long Retry-After window.
                if delay > 20:
                    break
                time.sleep(delay)
            assert response is not None
            if response.status_code >= 400:
                # API errors may contain echoed request contents. Never log the raw
                # provider response or any credentials, function source or prompts.
                safe_code = ""
                try:
                    err = response.json().get("error", {})
                    code = err.get("code") or err.get("type") or ""
                    if isinstance(code, str) and re.fullmatch(r"[a-zA-Z0-9_.-]{1,60}", code):
                        safe_code = f" ({code})"
                except (ValueError, AttributeError, TypeError):
                    pass
                hint = {400: "请求参数或上下文格式不合法；请检查模型、thinking、reasoning_content 和工具消息",
                        401: "API Key 无效或未授权", 402: "账户额度不足", 404: "模型名称或接口路径不存在",
                        413: "请求上下文过长", 429: "请求速率受限，请降低并发度"}.get(response.status_code,
                        "服务端调用失败，请检查供应商状态")
                retry_note = "（已进行有限重试）" if response.status_code in (429, 500, 502, 503, 504) else ""
                raise RuntimeError(f"模型服务接口 HTTP {response.status_code}{safe_code}{retry_note}：{hint}")
            payload = response.json()
        try:
            msg = payload["choices"][0]["message"]
            raw_calls = msg.get("tool_calls") or []
            calls = []
            for c in raw_calls:
                args = json.loads(c["function"].get("arguments") or "{}")
                if not isinstance(args, dict):
                    raise ValueError("工具参数必须为 JSON 对象")
                calls.append(ToolCall(id=str(c.get("id") or f"tool-call-{len(calls) + 1}"),
                                       name=c["function"]["name"], arguments=args))
            # Some OpenAI-compatible gateways may still expose the deprecated
            # single-function_call shape. Normalize it to tool_calls so the
            # Agent can process it through the same safe execution path.
            legacy_call = msg.get("function_call")
            if not calls and isinstance(legacy_call, dict) and legacy_call.get("name"):
                args = json.loads(legacy_call.get("arguments") or "{}")
                if not isinstance(args, dict):
                    raise ValueError("工具参数必须为 JSON 对象")
                calls.append(ToolCall(id="legacy-function-call-1",
                                      name=legacy_call["name"], arguments=args))
            clean_message = {"role": "assistant", "content": msg.get("content")}
            if calls:
                clean_message["tool_calls"] = [{"id": c.id, "type": "function", "function": {"name": c.name, "arguments": json.dumps(c.arguments, ensure_ascii=False)}} for c in calls]
            if msg.get("reasoning_content") is not None:
                # Required by DeepSeek thinking + tool-calls continuation.
                clean_message["reasoning_content"] = msg["reasoning_content"]
            finish_reason = payload["choices"][0].get("finish_reason")
            return ModelTurn(message=clean_message, calls=calls, finish_reason=finish_reason)
        except (KeyError, IndexError, TypeError, ValueError, json.JSONDecodeError) as exc:
            raise RuntimeError("模型没有返回符合规范的 function/tool_calls，当前模型不可用于自主 Agent") from exc
